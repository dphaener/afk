// TestRenderPaletteHubLabel checks which hub labels RenderPalette takes.
//
// The quote and newline rows are load-bearing: the label is written between
// double quotes in Lua without escaping, so a label that could hold `"` or a
// line break would let a typed label end the string and run code in the
// owner's palette. The 64- and 65-byte rows pin the bound on both sides. The
// leading-dash row keeps a label that reads as a flag out.
func TestRenderPaletteHubLabel(t *testing.T) {
	cases := []struct {
		name    string
		hub     string
		wantErr string // empty means the label is taken
	}{
		{name: "valid", hub: "vm"},
		{name: "valid with dot dash underscore", hub: "build-vm_2.local"},
		{name: "exactly 64 bytes", hub: strings.Repeat("a", 64)},
		{name: "empty", hub: "", wantErr: "the hub label is empty"},
		{name: "leading dash", hub: "-vm", wantErr: "must start with a letter or digit"},
		{name: "leading dot", hub: ".vm", wantErr: "must start with a letter or digit"},
		{name: "quote character", hub: `vm"; os.exit()`, wantErr: "cannot be used"},
		{name: "backslash", hub: `vm\`, wantErr: "cannot be used"},
		{name: "newline", hub: "vm\nos.exit()", wantErr: "cannot be used"},
		{name: "space", hub: "my vm", wantErr: "cannot be used"},
		{name: "over 64 bytes", hub: strings.Repeat("a", 65), wantErr: "at most 64"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			out, err := RenderPalette(tc.hub)
			if tc.wantErr != "" {
				if err == nil {
					t.Fatalf("RenderPalette(%q) took the label; want an error containing %q", tc.hub, tc.wantErr)
				}
				if !strings.Contains(err.Error(), tc.wantErr) {
					t.Fatalf("error %q does not contain %q", err, tc.wantErr)
				}
				if out != nil {
					t.Fatalf("RenderPalette(%q) returned output with its error", tc.hub)
				}
				return
			}
			if err != nil {
				t.Fatalf("RenderPalette(%q): %v", tc.hub, err)
			}
			if want := "local HUB = \"" + tc.hub + "\"\n"; !strings.Contains(string(out), want) {
				t.Fatalf("output has no %q line", strings.TrimSpace(want))
			}
		})
	}
}

// TestRenderPaletteOutput checks the generated file as text and as Lua.
//
// The parse row is load-bearing: it is the Lua syntax check the plan asks of
// make check, and the "missing end" row beside it proves the parser would
// catch a broken file rather than accept anything. The rex.bind row is
// load-bearing because the file must never take a key from the owner: a
// rex.bind outside a comment would bind one on every reload.
func TestRenderPaletteOutput(t *testing.T) {
	out, err := RenderPalette("vm")
	if err != nil {
		t.Fatal(err)
	}
	src := string(out)
	cases := []struct {
		name  string
		check func(t *testing.T)
	}{
		{name: "leading comment says generated", check: func(t *testing.T) {
			first := strings.SplitN(src, "\n", 2)[0]
			if !strings.HasPrefix(first, "--") {
				t.Fatalf("first line %q is not a comment", first)
			}
			if !strings.Contains(src[:400], "Generated by `afk rex setup`. Do not edit this file by hand") {
				t.Fatal("the opening comment does not say the file is generated and not to be edited")
			}
		}},
		{name: "every action name and title", check: func(t *testing.T) {
			for _, want := range []string{
				`name = "afk_control_room"`, `title = "afk: Open the control room"`,
				`name = "afk_next_needs_you"`, `title = "afk: Go to the next agent that needs you"`,
				`name = "afk_pause"`, `title = "afk: Pause the build"`,
				`name = "afk_resume"`, `title = "afk: Resume the build"`,
			} {
				if !strings.Contains(src, want) {
					t.Errorf("output has no %s", want)
				}
			}
			if n := strings.Count(src, `category = "afk"`); n != 4 {
				t.Errorf("%d actions in category afk; want 4", n)
			}
		}},
		{name: "rex.bind only in comments", check: func(t *testing.T) {
			commented := 0
			for i, line := range strings.Split(src, "\n") {
				if !strings.Contains(line, "rex.bind") {
					continue
				}
				if !strings.HasPrefix(strings.TrimSpace(line), "--") {
					t.Errorf("line %d binds a key outside a comment: %s", i+1, line)
				}
				commented++
			}
			if commented != 4 {
				t.Errorf("%d suggested keys in comments; want one per action (4)", commented)
			}
		}},
		{name: "parses as Lua", check: func(t *testing.T) {
			if _, err := parse.Parse(strings.NewReader(src), "afk.lua"); err != nil {
				t.Fatalf("the generated file is not valid Lua: %v", err)
			}
		}},
		{name: "parse rejects a missing end", check: func(t *testing.T) {
			i := strings.LastIndex(src, "end")
			broken := src[:i] + src[i+len("end"):]
			if _, err := parse.Parse(strings.NewReader(broken), "afk.lua"); err == nil {
				t.Fatal("the parser took the file with an end removed, so the parse row proves nothing")
			}
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, tc.check)
	}
}

// paletteFake is Lua run before the generated file: a stand-in for Rex's
// rex table, so the actions run in gopher-lua without any Rex. It follows
// what was pinned against the real rex CLI (docs/decisions.md ## T17.11):
// rex.server throws for an unknown label, and server.call returns nil and an
// error text for a failed call, and session.list_blocks, block.method,
// session.focus_window and session.new_window are refused with "stream is not attached to session"
// until session.attach names the session. Each case sets REPLIES, keyed by
// "method session_id block_id", to a reply table or {err = "..."}, and may
// set ATTACHED to the sessions the connection starts attached to; a missing
// key answers {}. The run's calls and logs come back from summary(), one line
// per call, with "refused " before a call that failed.
const paletteFake = `
calls, logs, actions = {}, {}, {}
KNOWN_HUB = KNOWN_HUB or "vm"
ATTACHED = ATTACHED or {}
local needs_attach = {["session.list_blocks"] = true, ["block.method"] = true, ["session.focus_window"] = true, ["session.new_window"] = true}
local function answer(method, args)
  if needs_attach[method] and not ATTACHED[args.session_id] then
    return nil, "stream response \"control-1\" failed: stream is not attached to session " .. tostring(args.session_id) .. " (status=409 code=conflict)"
  end
  local r = REPLIES[method .. " " .. tostring(args.session_id or "") .. " " .. tostring(args.block_id or "")]
  if r ~= nil and r.err then return nil, r.err end
  if method == "session.attach" then ATTACHED[args.session_id] = true end
  if method == "session.detach" then ATTACHED[args.session_id] = nil end
  return r or {}
end
rex = {
  action = function(a) actions[a.name] = a end,
  log = function(s) logs[#logs + 1] = s end,
  server = function(label)
    if label ~= KNOWN_HUB then
      error("rex.server: no host named \"" .. label .. "\": rex hosts lists the hosts this device knows")
    end
    return {call = function(method, args)
      local reply, err = answer(method, args)
      calls[#calls + 1] = {method = method, args = args, failed = reply == nil}
      return reply, err
    end}
  end,
}
function summary()
  local out = {}
  for _, c in ipairs(calls) do
    local a, line = c.args, nil
    if c.method == "session.focus_window" then
      line = "focus " .. a.session_id .. " " .. a.window_id
    elseif c.method == "session.new_window" then
      local o = a.layout.block.options
      line = "new_window " .. a.session_id .. " label=" .. a.window_label .. " flavor=" .. a.layout.block.flavor ..
        " command=" .. table.concat(o.command, ",") .. " on_completion=" .. tostring(o.exit.on_completion) ..
        " focus=" .. tostring(a.focus)
    elseif c.method == "session.list_blocks" then
      line = "list_blocks " .. a.session_id
    elseif c.method == "block.method" then
      line = "method " .. a.method .. " " .. a.block_id
    elseif c.method == "session.attach" or c.method == "session.detach" then
      line = string.sub(c.method, 9) .. " " .. a.session_id
    end
    if line then
      if c.failed then line = "refused " .. line end
      out[#out + 1] = line
    end
  end
  for _, l in ipairs(logs) do out[#out + 1] = "log " .. l end
  return table.concat(out, "\n")
end
`

// Replies the action rows share: a project session first, then the "afk"
// session with a pause window opened beside the control room.
const paletteSessions = `["session.list  "] = {sessions = {
    {session_id = "s-proj", label = "proj"},
    {session_id = "s-other", label = "other"},
    {session_id = "s-afk", label = "afk"},
  }},
  ["session.list_blocks s-afk "] = {blocks = {
    {block_id = "b-pause", label = "afk pause", placement = "placed", window_id = "w-pause"},
    {block_id = "b-room", label = "afk", placement = "placed", window_id = "w-room"},
  }},
`

// TestRenderPaletteActions runs each generated action against the stand-in
// Rex and checks the calls it makes and the lines it logs.
//
// Load-bearing rows: "control room picks the afk block" (the pause window
// is listed first, so taking the first window would land on the wrong
// one); "blocked beats an earlier error" (the plan's order is every blocked
// record before any error, not the first record of either); "detached block
// is skipped" (it has no window to focus); "unknown hub" and "call fails"
// (an unknown label or a failed call must become a log line naming the hub,
// never an error thrown in the owner's palette); the two attach rows (a real
// hub refuses session calls until the connection attaches, which is what
// broke the first version of this file against a scratch Rex server, and a
// session the connection was already attached to must not be detached under
// the owner's own view); and the pause rows (the terminal must close when
// done and run exactly `afk pause`).
func TestRenderPaletteActions(t *testing.T) {
	cases := []struct {
		name     string
		action   string
		replies  string   // Lua table body for REPLIES
		hub      string   // the label the stand-in knows; empty means "vm"
		attached string   // Lua table body for ATTACHED
		want     []string // each must start a line of the summary
		wantIn   []string // each must appear somewhere in the summary
		wantNot  []string // none may appear anywhere in the summary
		exact    string   // when set, the whole summary
	}{
		{
			name: "attaches only on refusal then detaches", action: "afk_control_room",
			replies: paletteSessions,
			exact: "refused list_blocks s-afk\nattach s-afk\nlist_blocks s-afk\ndetach s-afk\n" +
				"refused focus s-afk w-room\nattach s-afk\nfocus s-afk w-room\ndetach s-afk",
		},
		{
			name: "already attached session is left attached", action: "afk_control_room",
			replies: paletteSessions, attached: `["s-afk"] = true`,
			exact: "list_blocks s-afk\nfocus s-afk w-room",
		},
		{
			name: "attach fails", action: "afk_control_room",
			replies: paletteSessions + `["session.attach s-afk "] = {err = "session not found (status=404 code=session_not_found)"},`,
			want:    []string{`log afk: could not open the control room on the Rex host "vm": session not found`},
			wantNot: []string{"detach", "\nfocus"},
		},
		{
			name: "control room picks the afk block", action: "afk_control_room",
			replies: paletteSessions,
			want:    []string{"focus s-afk w-room"},
			wantNot: []string{"focus s-afk w-pause", "log"},
		},
		{
			name: "control room falls back to any open window", action: "afk_control_room",
			replies: `["session.list  "] = {sessions = {{session_id = "s-afk", label = "afk"}}},
  ["session.list_blocks s-afk "] = {blocks = {
    {block_id = "b-gone", label = "afk", placement = "detached"},
    {block_id = "b-x", label = "dash", placement = "placed", window_id = "w-x"},
  }},`,
			want: []string{"focus s-afk w-x"},
		},
		{
			name: "control room session missing", action: "afk_control_room",
			replies: `["session.list  "] = {sessions = {{session_id = "s-proj", label = "proj"}}},`,
			want:    []string{`log afk: could not open the control room on the Rex host "vm": it has no Rex session named "afk"`},
			wantNot: []string{"focus"},
		},
		{
			name: "control room with no open window", action: "afk_control_room",
			replies: `["session.list  "] = {sessions = {{session_id = "s-afk", label = "afk"}}},
  ["session.list_blocks s-afk "] = {blocks = {}},`,
			want:    []string{`log afk: could not open the control room on the Rex host "vm": the "afk" session has no open window`},
			wantNot: []string{"focus"},
		},
		{
			name: "control room with null lists", action: "afk_control_room",
			replies: `["session.list  "] = {},`,
			want:    []string{`log afk: could not open the control room on the Rex host "vm": it has no Rex session named "afk"`},
			wantNot: []string{"focus"},
		},
		{
			name: "unknown hub", action: "afk_control_room", hub: "elsewhere",
			want:    []string{`log afk: could not open the control room on the Rex host "vm": `},
			wantIn:  []string{`rex.server: no host named "vm"`},
			wantNot: []string{"focus"},
		},
		{
			name: "call fails", action: "afk_control_room",
			replies: `["session.list  "] = {err = "session.list failed (status=503 code=unavailable)"},`,
			want:    []string{`log afk: could not open the control room on the Rex host "vm": session.list failed (status=503 code=unavailable)`},
		},
		{
			name: "focus fails", action: "afk_control_room",
			replies: paletteSessions + `["session.focus_window s-afk "] = {err = "window not found (status=404 code=not_found)"},`,
			want:    []string{`log afk: could not open the control room on the Rex host "vm": window not found`},
		},
		{
			name: "blocked beats an earlier error", action: "afk_next_needs_you",
			replies: paletteSessions + `["session.list_blocks s-proj "] = {blocks = {{block_id = "b1", placement = "placed", window_id = "w1"}}},
  ["block.method s-proj b1"] = {records = {{state = "error", msg = "tests failed"}}},
  ["session.list_blocks s-other "] = {blocks = {{block_id = "b2", placement = "placed", window_id = "w2"}}},
  ["block.method s-other b2"] = {records = {{state = "working"}, {id = "afk", state = "blocked", kind = "permission", msg = "approve Bash: make check"}}},`,
			want:    []string{"method program_status b1", "focus s-other w2", "log afk: other: approve Bash: make check"},
			wantNot: []string{"focus s-proj"},
		},
		{
			name: "first error when nothing is blocked", action: "afk_next_needs_you",
			replies: paletteSessions + `["session.list_blocks s-proj "] = {blocks = {{block_id = "b1", placement = "placed", window_id = "w1"}}},
  ["block.method s-proj b1"] = {records = {{state = "error", msg = "tests failed"}}},
  ["session.list_blocks s-other "] = {blocks = {{block_id = "b2", placement = "placed", window_id = "w2"}}},
  ["block.method s-other b2"] = {records = {{state = "error", msg = "later"}}},`,
			want:    []string{"focus s-proj w1", "log afk: proj: tests failed"},
			wantNot: []string{"focus s-other"},
		},
		{
			name: "nobody needs you", action: "afk_next_needs_you",
			replies: paletteSessions + `["session.list_blocks s-proj "] = {blocks = {{block_id = "b1", placement = "placed", window_id = "w1"}}},
  ["block.method s-proj b1"] = {records = {{state = "working"}, {state = "done"}}},`,
			want:    []string{`log afk: no agent on the Rex host "vm" needs you right now`},
			wantNot: []string{"focus"},
		},
		{
			name: "detached block is skipped", action: "afk_next_needs_you",
			replies: paletteSessions + `["session.list_blocks s-proj "] = {blocks = {{block_id = "b1", placement = "detached"}}},
  ["block.method s-proj b1"] = {records = {{state = "blocked", msg = "hidden"}}},`,
			want:    []string{`log afk: no agent on the Rex host "vm" needs you right now`},
			wantNot: []string{"focus", "method program_status b1"},
		},
		{
			name: "a block without program status is skipped", action: "afk_next_needs_you",
			replies: paletteSessions + `["session.list_blocks s-proj "] = {blocks = {
    {block_id = "b-web", placement = "placed", window_id = "w-web"},
    {block_id = "b1", placement = "placed", window_id = "w1"},
  }},
  ["block.method s-proj b-web"] = {err = "no method program_status (status=404 code=method_not_found)"},
  ["block.method s-proj b1"] = {records = {{state = "blocked", kind = "question", msg = "answer: which branch?"}}},`,
			want: []string{"focus s-proj w1"},
		},
		{
			name: "a session that will not list is skipped", action: "afk_next_needs_you",
			replies: paletteSessions + `["session.list_blocks s-proj "] = {err = "session not found (status=404 code=session_not_found)"},
  ["session.list_blocks s-other "] = {blocks = {{block_id = "b2", placement = "placed", window_id = "w2"}}},
  ["block.method s-other b2"] = {records = {{state = "blocked"}}},`,
			want:    []string{"focus s-other w2"},
			wantNot: []string{"log"},
		},
		{
			name: "next needs you with unknown hub", action: "afk_next_needs_you", hub: "elsewhere",
			want: []string{`log afk: could not look for an agent that needs you on the Rex host "vm": `},
		},
		{
			name: "pause opens a closing terminal", action: "afk_pause",
			replies: paletteSessions,
			want: []string{
				"new_window s-afk label=afk pause flavor=com.superlogical.terminal.shell command=afk,pause on_completion=true focus=true",
				`log afk: asked the Rex host "vm" to pause the build`,
			},
		},
		{
			name: "resume opens a closing terminal", action: "afk_resume",
			replies: paletteSessions,
			want: []string{
				"new_window s-afk label=afk resume flavor=com.superlogical.terminal.shell command=afk,resume on_completion=true focus=true",
				`log afk: asked the Rex host "vm" to resume the build`,
			},
		},
		{
			name: "pause with no afk session", action: "afk_pause",
			replies: `["session.list  "] = {sessions = {}},`,
			want:    []string{`log afk: could not pause the build on the Rex host "vm": it has no Rex session named "afk"`},
			wantNot: []string{"new_window", "asked"},
		},
		{
			name: "pause when the window will not open", action: "afk_pause",
			replies: paletteSessions + `["session.new_window s-afk "] = {err = "window limit reached (status=409 code=conflict)"},`,
			want:    []string{`log afk: could not pause the build on the Rex host "vm": window limit reached`},
			wantNot: []string{"asked"},
		},
	}
	out, err := RenderPalette("vm")
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			L := lua.NewState()
			defer L.Close()
			hub := tc.hub
			if hub == "" {
				hub = "vm"
			}
			setup := "KNOWN_HUB = \"" + hub + "\"\nATTACHED = {" + tc.attached + "}\nREPLIES = {\n" + tc.replies + "\n}\n" + paletteFake
			if err := L.DoString(setup); err != nil {
				t.Fatalf("stand-in Rex: %v", err)
			}
			if err := L.DoString(string(out)); err != nil {
				t.Fatalf("loading the generated file: %v", err)
			}
			if err := L.DoString(`
local n = 0
for _ in pairs(actions) do n = n + 1 end
assert(n == 4, "want 4 actions, got " .. n)
actions["` + tc.action + `"].run({})
RESULT = summary()`); err != nil {
				t.Fatalf("running %s threw instead of logging: %v", tc.action, err)
			}
			got := L.GetGlobal("RESULT").String()
			if tc.exact != "" && got != tc.exact {
				t.Errorf("summary:\n%s\nwant:\n%s", got, tc.exact)
			}
			lines := strings.Split(got, "\n")
			for _, w := range tc.want {
				found := false
				for _, l := range lines {
					found = found || strings.HasPrefix(l, w)
				}
				if !found {
					t.Errorf("no line starts with %q in:\n%s", w, got)
				}
			}
			for _, w := range tc.wantIn {
				if !strings.Contains(got, w) {
					t.Errorf("missing %q in:\n%s", w, got)
				}
			}
			for _, w := range tc.wantNot {
				if strings.Contains(got, w) {
					t.Errorf("unexpected %q in:\n%s", w, got)
				}
			}
		})
	}
}
